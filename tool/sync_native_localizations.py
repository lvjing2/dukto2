#!/usr/bin/env python3
"""Generate Apple's OS-owned permission strings from the same ARB catalogs.

Run after editing translations; --check verifies committed resources in CI.
System permission dialogs follow the OS app language, not Dart's live preference.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCALES = {'en': 'en', 'zh_Hans': 'zh-Hans', 'es': 'es', 'pt_BR': 'pt-BR',
           'fr': 'fr', 'de': 'de', 'ru': 'ru', 'ja': 'ja', 'ko': 'ko', 'ar': 'ar'}


def resources():
    for arb_locale, apple_locale in LOCALES.items():
        data = json.loads((ROOT / f'lib/l10n/app_{arb_locale}.arb').read_text())
        text = '// Generated by tool/sync_native_localizations.py from ARB.\n'
        text += f'"NSLocalNetworkUsageDescription" = {json.dumps(data["networkPermission"], ensure_ascii=False)};\n'
        text += f'"NSCameraUsageDescription" = {json.dumps(data["qrAim"], ensure_ascii=False)};\n'
        for platform in ('ios', 'macos'):
            yield ROOT / platform / 'Runner' / f'{apple_locale}.lproj' / 'InfoPlist.strings', text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outdated = []
    for path, expected in resources():
        if args.check:
            if not path.exists() or path.read_text() != expected:
                outdated.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    if outdated:
        raise SystemExit('Run python3 tool/sync_native_localizations.py:\n' + '\n'.join(outdated))


if __name__ == '__main__':
    main()
